// Upstream packaging bug: @shopify/shopify-app-react-router@1.2.1 ships
// dist/ts/server/index.d.ts.map but not the index.d.ts itself, so TypeScript
// reports TS7016 for `@shopify/shopify-app-react-router/server`.
// We regenerate the barrel from the concrete sub-declaration files (which DO
// ship), preserving full type information. Idempotent; runs on postinstall.
import { existsSync, writeFileSync } from "node:fs";
import { join } from "node:path";

const base = join(
  process.cwd(),
  "node_modules",
  "@shopify",
  "shopify-app-react-router",
  "dist",
  "ts",
  "server",
);

const target = join(base, "index.d.ts");

// Mirrors dist/esm/server/index.mjs re-exports.
const contents = `// Regenerated by scripts/patch-shopify-types.mjs (upstream barrel .d.ts missing).
export { ApiVersion, BillingInterval, BillingReplacementBehavior, DeliveryMethod, LogSeverity, Session } from '@shopify/shopify-api';
export { AppDistribution, LoginErrorType } from './types';
export { boundary } from './boundary/index';
export { shopifyApp } from './shopify-app';
export { SessionNotFoundError } from './errors';
export * from './types';
`;

if (!existsSync(base)) {
  // Package not installed (e.g. CI cache miss) — nothing to patch.
  process.exit(0);
}

if (!existsSync(target)) {
  writeFileSync(target, contents, "utf8");
  console.log("✔ Patched missing shopify-app-react-router server types.");
} else {
  // Already present (fixed upstream or previously patched) — leave it.
}
